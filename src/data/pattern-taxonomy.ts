export function getProblemPatterns(problem: PatternSource) {
  const matched = RULES.find((rule) => rule.match.test(problem.title))?.patterns ?? []
  const defaults = TOPIC_DEFAULTS[problem.topic] ?? [problem.topic]
  return [...new Set([...matched, ...defaults])].slice(0, 3)
}